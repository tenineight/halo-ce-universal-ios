#!/usr/bin/env python3
"""Generate the WebAssembly guest's OpenGL ES bridge, both halves.

The guest (port/wasm/README.md) calls OpenGL ES through imports of module
"halo" named hostgl_<function>, one for each function in the ES list of
port/linux/src/gl.h. Its side (guest_gl.c) is the table that
SDL_GL_GetProcAddress (guest_sdl.c) hands out: the imports themselves, so a
call costs nothing more than an import call. Only glGetString needs a guest
function, as the string has to be copied into guest memory.

The host's side (host_gl_bridge.c, for wasm2c's naming of the imports)
gives each import its C prototype, turns guest pointers into host pointers
and calls the driver's function, which host_gl_load resolves through SDL
once the context exists. Not every pointer parameter is a pointer: the
renderer always draws from buffer objects, so the vertex attribute pointer
and the index pointer of a draw are offsets into the bound buffer, and pass
unchanged. The host's own helpers (port/macos/host/host_gl.c) call the
driver through the same table (host_gl_functions.h), which therefore also
holds the functions in HOST_ONLY.

Usage: wasm_gl_stubs.py gl.h gl32.h gl2ext.h guest_gl.c host_gl_bridge.c host_gl_functions.h
"""

import re
import sys

# parameters that are offsets into the bound buffer object, not pointers
OFFSET_PARAMETERS = {
    ("glVertexAttribPointer", "pointer"),
    ("glVertexAttribIPointer", "pointer"),
    ("glDrawElements", "indices"),
    ("glDrawElementsBaseVertex", "indices"),
    ("glDrawRangeElements", "indices"),
    ("glDrawElementsInstanced", "indices"),
}
# the host's helpers' functions (host_gl.c), beyond the guest's
HOST_ONLY = [
    "glGetStringi", "glMapBufferRange", "glUnmapBuffer", "glFenceSync", "glClientWaitSync", "glDeleteSync",
]
FLOAT_TYPES = {"GLfloat": "f32", "GLclampf": "f32", "float": "f32", "GLdouble": "f64", "double": "f64"}
WIDE_TYPES = {"GLint64", "GLuint64", "GLint64EXT", "GLuint64EXT"}
POINTER_SIZED = {"GLsizeiptr", "GLintptr"}


def es_functions(gl_header: str):
    text = open(gl_header, encoding="utf-8").read()
    start = text.index("/* ANDROID_GL_FUNCTIONS_BEGIN */")
    end = text.index("/* ANDROID_GL_FUNCTIONS_END */")
    return re.findall(r"X\((\w+)\)", text[start:end])


def prototypes(*headers):
    result = {}
    pattern = re.compile(r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\((.*?)\);", re.S)
    for header in headers:
        text = open(header, encoding="utf-8").read()
        for ret, name, params in pattern.findall(text):
            result.setdefault(name, (" ".join(ret.split()), " ".join(params.split())))
    return result


def split_parameters(params: str):
    if params in ("void", ""):
        return []
    result = []
    for param in params.split(","):
        param = param.strip()
        m = re.match(r"(.*?)(\w+)\s*$", param)
        ptype, pname = m.group(1).strip(), m.group(2)
        result.append((ptype, pname))
    return result


def wasm_type(ctype: str) -> str:
    """the wasm2c type of a value of this C type in the guest"""
    if "*" in ctype:
        return "u32"
    base = ctype.replace("const", "").strip()
    if base in FLOAT_TYPES:
        return FLOAT_TYPES[base]
    if base in WIDE_TYPES:
        return "u64"
    if base == "void":
        return "void"
    return "u32"


# the ES 3.2 functions the renderer does without on an ES 3.0 driver
# (iOS's): it checks xgpu_capabilities before calling them (d3d8_gl.c)
OPTIONAL = {"glCopyImageSubData", "glDrawElementsBaseVertex"}


def main():
    gl_header, gl32, gl2ext, guest_output, host_output, host_header = sys.argv[1:7]
    functions = es_functions(gl_header)
    protos = prototypes(gl32, gl2ext)
    for name in functions + HOST_ONLY:
        if name not in protos:
            raise SystemExit(f"{name}: no prototype in the GLES headers")

    # ---------- the guest
    guest = [
        "/* generated by tools/wasm_gl_stubs.py from port/linux/src/gl.h; do not edit */",
        "#include <GLES3/gl32.h>",
        "#include <GLES2/gl2ext.h>",
        "#include <string.h>",
        '#include "guest_host.h"',
        "",
    ]
    table = []
    for name in functions:
        ret, params = protos[name]
        if name == "glGetString":
            guest += [
                "static const GLubyte *GL_APIENTRY guest_glGetString(GLenum name)",
                "{",
                "\tstatic __thread char buffer[4][4096];",
                "\tstatic __thread int next;",
                "\tchar *result = buffer[next++ & 3];",
                "",
                "\thost_gl_get_string(name, -1, result, sizeof(buffer[0]));",
                "\treturn (const GLubyte *)result;",
                "}",
                "",
            ]
            table.append((name, "guest_glGetString"))
            continue
        if "*" in ret:
            raise SystemExit(f"{name}: returns a pointer; add a special case")
        if "GLsync" in params or "GLsync" in ret:
            raise SystemExit(f"{name}: takes a host object (GLsync); add a special case")
        guest.append(f"{ret} HOST_IMPORT(hostgl_{name})({params or 'void'});")
        table.append((name, f"hostgl_{name}"))
    guest += [
        "",
        "static const struct { const char *name; void *function; } guest_gl_functions[] =",
        "{",
        *(f'\t{{ "{name}", (void *){function} }},' for name, function in table),
        "};",
        "",
        "typedef void (*guest_gl_function)(void);",
        "guest_gl_function guest_gl_get_proc_address(const char *name)",
        "{",
        "\tunsigned long index;",
        "",
        "\tfor (index = 0; index < sizeof(guest_gl_functions) / sizeof(guest_gl_functions[0]); index++)",
        "\t{",
        "\t\tif (!strcmp(guest_gl_functions[index].name, name))",
        "\t\t\treturn (guest_gl_function)guest_gl_functions[index].function;",
        "\t}",
        "\treturn 0;",
        "}",
    ]
    with open(guest_output, "w", encoding="utf-8") as f:
        f.write("\n".join(guest) + "\n")

    # ---------- the host's table of driver functions
    host_functions = [name for name in functions] + [name for name in HOST_ONLY if name not in functions]
    header = [
        "/* generated by tools/wasm_gl_stubs.py from port/linux/src/gl.h; do not edit */",
        "#ifndef __HOST_GL_FUNCTIONS_H",
        "#define __HOST_GL_FUNCTIONS_H",
        "#include <GLES3/gl32.h>",
        "#include <GLES2/gl2ext.h>",
        "",
        "/* the driver's functions, once host_gl_load has resolved them */",
    ]
    for name in host_functions:
        ret, params = protos[name]
        header.append(f"extern {ret} (GL_APIENTRY *host_{name})({params or 'void'});")
    header += [
        "",
        "/* resolves them with SDL_GL_GetProcAddress, for the current context; 0 if one is missing */",
        "int host_gl_load(void);",
        "",
        "#endif",
    ]
    with open(host_header, "w", encoding="utf-8") as f:
        f.write("\n".join(header) + "\n")

    # ---------- the host's imports
    host = [
        "/* generated by tools/wasm_gl_stubs.py from port/linux/src/gl.h; do not edit */",
        "#include <SDL3/SDL.h>",
        "#include <stdint.h>",
        '#include "host.h"',
        '#include "host_gl_functions.h"',
        "",
    ]
    for name in host_functions:
        ret, params = protos[name]
        host.append(f"{ret} (GL_APIENTRY *host_{name})({params or 'void'});")
    host += [
        "",
        "int host_gl_load(void)",
        "{",
        "\tint missing = 0;",
        "",
    ]
    for name in host_functions:
        host.append(f'\tif (!(*(void **)&host_{name} = (void *)SDL_GL_GetProcAddress("{name}")))')
        if name in OPTIONAL:
            host.append(f'\t\thost_logf("OpenGL ES function {name} is missing (the renderer does without)");')
        else:
            host.append(f'\t\thost_logf("OpenGL ES function {name} is missing"), missing++;')
    host += ["\treturn missing == 0;", "}", ""]
    for name in functions:
        if name == "glGetString":
            continue
        ret, params = protos[name]
        plist = split_parameters(params)
        wret = wasm_type(ret)
        decl = ["struct w2c_halo *instance"]
        args = []
        for index, (ptype, pname) in enumerate(plist):
            wtype = wasm_type(ptype)
            arg = f"a{index}"
            decl.append(f"{wtype} {arg}")
            base = ptype.replace("const", "").strip()
            if "*" in ptype:
                if (name, pname) in OFFSET_PARAMETERS:
                    args.append(f"({ptype})(uintptr_t){arg}")
                elif ptype.replace(" ", "").count("*") > 1:
                    # an array of string pointers (glShaderSource)
                    args.append(f"({ptype})host_guest_pointer_array({arg}, a1)")
                else:
                    args.append(f"({ptype})host_guest_pointer({arg})")
            elif base in POINTER_SIZED:
                args.append(f"({ptype})(int32_t){arg}")
            else:
                args.append(f"({ptype}){arg}")
        call = f"host_{name}({', '.join(args)})"
        host.append(f"{wret} w2c_halo_hostgl_{name}({', '.join(decl)})")
        host.append("{")
        host.append("\t(void)instance;")
        if wret == "void":
            host.append(f"\t{call};")
        else:
            host.append(f"\treturn ({wret}){call};")
        host.append("}")
        host.append("")
    with open(host_output, "w", encoding="utf-8") as f:
        f.write("\n".join(host) + "\n")


if __name__ == "__main__":
    main()
