#!/usr/bin/env python3
"""Generate the WebAssembly guest's side and its host's side of
port/linux/src/posix.h.

The posix_*.c helpers run in the host (port/wasm/README.md), as on Android:
they are the platform layer's only contact with the system's file system
and sockets. Their interface is 32-bit clean, so a guest call becomes an
import of module "halo" named hostposix_<name> with the same arguments,
whose host side turns guest pointers into host pointers. Two things do not
cross as they are:

- errno: the guest's is not the host's; each guest wrapper copies the
  host's into its own afterwards (host_errno translates the value);
- the directory handle of posix_directory_*, a host pointer, which the
  guest holds as a small handle instead (host_handle_*).

Usage: wasm_posix_stubs.py posix.h guest_posix.c host_posix_bridge.c
"""

import re
import sys

HANDLE_TYPE = "void *"


def parse(header):
    text = open(header, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    result = []
    for ret, name, params in re.findall(r"^([A-Za-z_][\w \*]*?)\b(posix_\w+)\s*\(([^;]*?)\);", text, re.M | re.S):
        ret = " ".join(ret.split())
        params = " ".join(params.split())
        plist = []
        if params != "void":
            for param in params.split(","):
                m = re.match(r"(.*?)(\w+)\s*$", param.strip())
                plist.append((" ".join(m.group(1).split()), m.group(2)))
        result.append((ret, name, plist))
    return result


def is_handle(ctype, pname=None):
    return ctype.replace(" ", "") == "void*" and (pname is None or pname == "directory")


def main():
    header, guest_output, host_output = sys.argv[1:4]
    functions = parse(header)

    guest = [
        "/* generated by tools/wasm_posix_stubs.py from port/linux/src/posix.h; do not edit */",
        "#include <errno.h>",
        '#include "posix.h"',
        '#include "guest_host.h"',
        "",
    ]
    host = [
        "/* generated by tools/wasm_posix_stubs.py from port/linux/src/posix.h; do not edit */",
        "#include <stdint.h>",
        '#include "host.h"',
        '#include "posix.h"',
        "",
    ]
    for ret, name, plist in functions:
        host_name = "hostposix_" + name[len("posix_"):]
        params = ", ".join(f"{ptype} {pname}" for ptype, pname in plist) or "void"
        args = ", ".join(pname for _, pname in plist)
        # the guest: the import, and the wrapper that takes over errno
        guest.append(f"{ret} HOST_IMPORT({host_name})({params});")
        guest.append(f"{ret} {name}({params})")
        guest.append("{")
        if ret == "void":
            guest.append(f"\t{host_name}({args});")
            guest.append("\terrno = host_errno();")
        else:
            guest.append(f"\t{ret} host_result = {host_name}({args});")
            guest.append("")
            guest.append("\terrno = host_errno();")
            guest.append("\treturn host_result;")
        guest.append("}")
        guest.append("")
        # the host: the import's definition
        wret = "void" if ret == "void" else "u32"
        decl = ["struct w2c_halo *instance"]
        call_args = []
        for index, (ptype, pname) in enumerate(plist):
            arg = f"a{index}"
            decl.append(f"u32 {arg}")
            if is_handle(ptype, pname):
                call_args.append(f"host_handle_get({arg})")
            elif "*" in ptype:
                call_args.append(f"({ptype})host_guest_pointer({arg})")
            elif ptype in ("posix_long", "int", "short"):
                call_args.append(f"({ptype})(int32_t){arg}")
            else:
                call_args.append(f"({ptype}){arg}")
        call = f"{name}({', '.join(call_args)})"
        host.append(f"{wret} w2c_halo_{host_name}({', '.join(decl)})")
        host.append("{")
        host.append("\t(void)instance;")
        if ret == "void":
            if name == "posix_directory_close":
                host.append(f"\t{call};")
                host.append("\thost_handle_free(a0);")
            else:
                host.append(f"\t{call};")
        elif is_handle(ret):
            host.append(f"\treturn host_handle_new({call});")
        else:
            host.append(f"\treturn (u32){call};")
        host.append("}")
        host.append("")
    with open(guest_output, "w", encoding="utf-8") as f:
        f.write("\n".join(guest))
    with open(host_output, "w", encoding="utf-8") as f:
        f.write("\n".join(host))


if __name__ == "__main__":
    main()
