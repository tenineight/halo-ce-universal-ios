bool SDL_ShowMessageBox(const SDL_MessageBoxData *data, int *buttonid)
{
	struct guest_message_box_button buttons[8];
	int count = data->numbuttons < 8 ? data->numbuttons : 8;
	int index, answer = -1;
	bool result;

	for (index = 0; index < count; index++)
	{
		buttons[index].flags = data->buttons[index].flags;
		buttons[index].id = data->buttons[index].buttonID;
		buttons[index].text = data->buttons[index].text;
	}
	result = host_sdl_show_message_box((unsigned int)data->flags, data->title, data->message, buttons, count,
		&answer) != 0;
	if (buttonid)
		*buttonid = answer;
	return result;
}

/* The host shows the dialog and waits for the player (the guest's main
thread is the host's), so the callback runs before this returns. */
void SDL_ShowOpenFileDialog(SDL_DialogFileCallback callback, void *userdata, SDL_Window *window,
	const SDL_DialogFileFilter *filters, int nfilters, const char *default_location, bool allow_many)
{
	char text[1024] = "";
	char path[1024];
	const char *files[2];
	int index;

	(void)window;
	(void)default_location;
	(void)allow_many;
	for (index = 0; index < nfilters; index++)
	{
		size_t length = strlen(text);

		snprintf(text + length, sizeof(text) - length, "%s\t%s\n", filters[index].name, filters[index].pattern);
	}
	host_sdl_choose_file(text, path, sizeof(path));
	files[0] = path;
	files[1] = NULL;
	callback(userdata, path[0] ? files : files + 1, -1);
}

