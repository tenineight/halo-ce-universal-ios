static const SDL_DisplayMode *display_mode(SDL_DisplayID display, int which)
{
	/* SDL keeps its modes; so does this, one per display and kind */
	static SDL_DisplayMode modes[8][2];
	static SDL_DisplayID displays[8];
	struct guest_display_mode mode;
	SDL_DisplayMode *result;
	int slot;

	if (!host_sdl_display_mode((unsigned int)display, which, &mode))
		return NULL;
	for (slot = 0; slot < 7 && displays[slot] && displays[slot] != display; slot++)
		;
	displays[slot] = display;
	result = &modes[slot][which];
	memset(result, 0, sizeof(*result));
	result->displayID = display;
	result->format = (SDL_PixelFormat)mode.format;
	result->w = mode.w;
	result->h = mode.h;
	result->pixel_density = mode.pixel_density;
	result->refresh_rate = mode.refresh_rate;
	result->refresh_rate_numerator = mode.refresh_rate_numerator;
	result->refresh_rate_denominator = mode.refresh_rate_denominator;
	return result;
}

const SDL_DisplayMode *SDL_GetDesktopDisplayMode(SDL_DisplayID display)
{
	return display_mode(display, 0);
}

const SDL_DisplayMode *SDL_GetCurrentDisplayMode(SDL_DisplayID display)
{
	return display_mode(display, 1);
}

