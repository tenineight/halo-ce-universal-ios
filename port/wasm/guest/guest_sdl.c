void *SDL_LoadFile(const char *file, size_t *datasize)
{
	FILE *stream = fopen(file, "rb");
	char *data = NULL;
	size_t size = 0, capacity = 0;

	if (datasize)
		*datasize = 0;
	if (!stream)
		return NULL;
	for (;;)
	{
		size_t read;

		if (size + 1 >= capacity)
		{
			char *grown;

			capacity = capacity ? capacity * 2 : 65536;
			grown = realloc(data, capacity);
			if (!grown)
			{
				free(data);
				fclose(stream);
				return NULL;
			}
			data = grown;
		}
		read = fread(data + size, 1, capacity - size - 1, stream);
		if (!read)
			break;
		size += read;
	}
	fclose(stream);
	/* SDL terminates what it loads */
	data[size] = 0;
	if (datasize)
		*datasize = size;
	return data;
}

bool SDL_SaveFile(const char *file, const void *data, size_t datasize)
{
	FILE *stream = fopen(file, "wb");
	bool written;

	if (!stream)
		return false;
	written = fwrite(data, 1, datasize, stream) == datasize;
	return fclose(stream) == 0 && written;
}

struct glob_result
{
	char **names;
	int count;
	int capacity;
};

static void glob_add(struct glob_result *result, const char *name)
{
	if (result->count + 1 >= result->capacity)
	{
		int capacity = result->capacity ? result->capacity * 2 : 16;
		char **names = realloc(result->names, (size_t)capacity * sizeof(char *));

		if (!names)
			return;
		result->names = names;
		result->capacity = capacity;
	}
	result->names[result->count++] = strdup(name);
}

/* the entries of folder/prefix matching pattern, as prefix/name */
static void glob_folder(struct glob_result *result, const char *folder, const char *prefix, const char *pattern)
{
	char path[1024];
	DIR *directory;
	struct dirent *entry;

	snprintf(path, sizeof(path), "%s/%s", folder, prefix);
	directory = opendir(path);
	if (!directory)
		return;
	while ((entry = readdir(directory)) != NULL)
	{
		char name[1024];

		if (entry->d_name[0] == '.' || fnmatch(pattern, entry->d_name, 0) != 0)
			continue;
		snprintf(name, sizeof(name), "%s%s", prefix, entry->d_name);
		glob_add(result, name);
	}
	closedir(directory);
}

/* the patterns the menus use: "name" and "folder/name", each part with
wildcards (SDL's * does not cross a /) */
char **SDL_GlobDirectory(const char *path, const char *pattern, SDL_GlobFlags flags, int *count)
{
	struct glob_result result = { NULL, 0, 0 };
	const char *slash = pattern ? strchr(pattern, '/') : NULL;
	char **list;
	size_t size;
	int index;
	char *strings;

	(void)flags;
	if (!pattern)
		pattern = "*";
	if (!slash)
	{
		glob_folder(&result, path, "", pattern);
	}
	else
	{
		char folder_pattern[256];
		DIR *directory = opendir(path);
		struct dirent *entry;

		snprintf(folder_pattern, sizeof(folder_pattern), "%.*s", (int)(slash - pattern), pattern);
		while (directory && (entry = readdir(directory)) != NULL)
		{
			char prefix[512];

			if (entry->d_name[0] == '.' || entry->d_type != DT_DIR || fnmatch(folder_pattern, entry->d_name, 0) != 0)
				continue;
			snprintf(prefix, sizeof(prefix), "%s/", entry->d_name);
			glob_folder(&result, path, prefix, slash + 1);
		}
		if (directory)
			closedir(directory);
	}
	/* as SDL: one allocation, freed with SDL_free */
	size = (size_t)(result.count + 1) * sizeof(char *);
	for (index = 0; index < result.count; index++)
		size += strlen(result.names[index]) + 1;
	list = malloc(size);
	if (list)
	{
		strings = (char *)(list + result.count + 1);
		for (index = 0; index < result.count; index++)
		{
			size_t length = strlen(result.names[index]) + 1;

			memcpy(strings, result.names[index], length);
			list[index] = strings;
			strings += length;
		}
		list[result.count] = NULL;
	}
	for (index = 0; index < result.count; index++)
		free(result.names[index]);
	free(result.names);
	if (count)
		*count = list ? result.count : 0;
	return list;
}

