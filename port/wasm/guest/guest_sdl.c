/* ---------- audio */

struct audio_callback
{
	unsigned int stream;
	SDL_AudioStreamCallback callback;
	void *userdata;
};

static void *audio_thread(void *context)
{
	struct audio_callback *binding = context;
	int additional, total;

	while (host_sdl_audio_wait(binding->stream, &additional, &total))
	{
		binding->callback(binding->userdata, (SDL_AudioStream *)binding->stream, additional, total);
		host_sdl_audio_done(binding->stream);
	}
	free(binding);
	return NULL;
}

SDL_AudioStream *SDL_OpenAudioDeviceStream(SDL_AudioDeviceID device, const SDL_AudioSpec *spec,
	SDL_AudioStreamCallback callback, void *userdata)
{
	unsigned int stream = host_sdl_open_audio_stream(device, spec, callback != NULL);

	if (stream && callback)
	{
		struct audio_callback *binding = malloc(sizeof(*binding));
		pthread_t thread;

		/* the device starts paused: no request comes before the thread
		waits for it */
		binding->stream = stream;
		binding->callback = callback;
		binding->userdata = userdata;
		if (pthread_create(&thread, NULL, audio_thread, binding) != 0)
		{
			free(binding);
			return NULL;
		}
		pthread_detach(thread);
	}
	return (SDL_AudioStream *)stream;
}

